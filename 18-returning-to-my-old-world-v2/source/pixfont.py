def glyph(ch):
    g = G.get(ch) or G.get(ch.lower()) or G[' ']
    return np.array([[c == '#' for c in row.ljust(len(g[0]))] for row in g], bool)


def text_mask(s, gap=1):
    """boolean mask (7 rows) of a string"""
    cols = []
    for ch in s:
        g = glyph(ch)
        cols.append(g); cols.append(np.zeros((7, gap), bool))
    return np.concatenate(cols[:-1], 1) if cols else np.zeros((7, 1), bool)
